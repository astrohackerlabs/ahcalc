/**
 * Product compile: write embedded version, RR production build, one
 * bun --compile binary for CLI. Stamp: package.json version (ahcalc is
 * versioned independently of TermSurf).
 *
 * RR server assets live in build/; CLI binary still dist/ahcalc.
 * TermSurf server role expects `build/server` present next to package root.
 */
import * as fs from "node:fs";
import * as path from "node:path";

const root = path.resolve(import.meta.dir, "..");
const pkg = JSON.parse(
  fs.readFileSync(path.join(root, "package.json"), "utf8"),
) as {
  version?: string;
};

const version = typeof pkg.version === "string" ? pkg.version : "0.0.1";

const embedPath = path.join(root, "app/cli/embedded-version.ts");
const embedSource = `/**
 * Generated by scripts/build-ahcalc.ts at compile time.
 * Do not hand-edit for releases — set package.json version and rebuild.
 */
export const AHCALC_EMBEDDED_VERSION = ${JSON.stringify(version)};
`;
fs.writeFileSync(embedPath, embedSource, "utf8");
console.log(`build-ahcalc: wrote ${embedPath} = ${version}`);

const rr = Bun.spawnSync(["bun", "run", "build"], {
  cwd: root,
  stdout: "inherit",
  stderr: "inherit",
});
if (rr.exitCode !== 0) {
  process.exit(rr.exitCode);
}

fs.mkdirSync(path.join(root, "dist"), { recursive: true });
try {
  fs.unlinkSync(path.join(root, "dist", "ahcalc-server"));
} catch {
  /* */
}

const compile = Bun.spawnSync(
  [
    "bun",
    "build",
    "--compile",
    "--keep-names",
    "--outfile",
    "dist/ahcalc",
    "cli.ts",
  ],
  {
    cwd: root,
    stdout: "inherit",
    stderr: "inherit",
  },
);
if (compile.exitCode !== 0) {
  process.exit(compile.exitCode);
}

const out = path.join(root, "dist", "ahcalc");
if (!fs.existsSync(out)) {
  console.error(`build-ahcalc: missing ${out}`);
  process.exit(1);
}
console.log(`build-ahcalc: wrote ${out}`);
